import fs from 'node:fs';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('./backup-restore-v2.js',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const webSource=fs.readFileSync(new URL('./web/backup-restore-v2.js',import.meta.url),'utf8');
const webHtml=fs.readFileSync(new URL('./web/index.html',import.meta.url),'utf8');
const sw=fs.readFileSync(new URL('./sw.js',import.meta.url),'utf8');
const webSw=fs.readFileSync(new URL('./web/sw.js',import.meta.url),'utf8');
assert.match(source,/ABA-English-Dictionary-v2/);
assert.match(source,/AmoozeshBaAmirLibrary/);
assert.match(source,/__abaBackupType:'Blob'/);
assert.match(source,/schemaVersion:4/);
assert.match(source,/window\.exportFullBackup/);
assert.match(source,/window\.importFullBackup/);
assert.match(html,/<script src="backup-restore-v2\.js"><\/script>/);
assert.equal(source,webSource,'root and web backup managers must be synchronized');
assert.equal(html,webHtml,'root and web HTML must be synchronized');
assert.equal(sw,webSw,'root and web service workers must be synchronized');
assert.match(sw,/amoozesh-ba-amir-v93/);
assert.match(sw,/backup-restore-v2\.js/);
console.log('IndexedDB backup readiness checks passed.');
