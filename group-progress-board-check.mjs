import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('./group-progress-board-v1.js',import.meta.url),'utf8');
const root=await readFile(new URL('./index.html',import.meta.url),'utf8');
const web=await readFile(new URL('./web/index.html',import.meta.url),'utf8');
assert.ok(root.includes('group-progress-board-v1.js'),'web app must load the A3 group board');
assert.ok(web.includes('group-progress-board-v1.js'),'Android web bundle must load the A3 group board');
const store={};
const localStorage={getItem:k=>store[k]??null,setItem:(k,v)=>{store[k]=String(v)}};
const listeners={};
const window={addEventListener:(n,f)=>(listeners[n]??=[]).push(f)};
const document={readyState:'loading',addEventListener(){},getElementById(){return null}};
const context={window,document,localStorage,Date,JSON,Math,String,Number,Object,Array,console};
vm.createContext(context);vm.runInContext(source,context);
const api=window.AbaGroupBoard,s=api.snapshot();
assert.equal(s.groupCount,4);
assert.equal(s.groups.length,4);
assert.ok(s.groups.every(g=>g.weeks.length===36),'each group must have 36 weekly slots');
assert.equal(api.months.length,9,'the board must cover nine school months');
const result=api.calculate({weeks:Array.from({length:36},(_,i)=>({score:[10,20,15][i]??''}))});
assert.equal(result.count,3);
assert.equal(result.total,45);
assert.equal(result.average,15);
assert.equal(result.months[0],15);
assert.equal(result.months[1],null);
api.switchUser('teacher-A');
assert.equal(api.snapshot().groupCount,4);
api.switchUser('teacher-B');
assert.equal(api.snapshot().groupCount,4);
api.switchUser('guest');
assert.equal(api.snapshot().groups.length,4);
console.log('PASS: A3 board has 9 months × 4 weeks, per-group calculations and account-scoped storage.');
