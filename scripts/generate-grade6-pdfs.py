def draw_pdf(path,chapter,title,pages,kind):
    c=canvas.Canvas(str(path),pagesize=A4); w,h=A4
    c.setTitle('کاربرگ ریاضی ششم - '+title)
    c.setFont('NotoArabic',19); c.drawRightString(w-42,h-54,fa('آموزش با امیر | کاربرگ ریاضی ششم'))
    c.setFont('NotoArabic',15); c.drawRightString(w-42,h-88,fa('فصل '+chapter+' - '+title))
    c.setFont('NotoArabic',10); c.drawRightString(w-42,h-112,fa('مطابق محدودهٔ صفحه '+pages+' کتاب درسی | تمرین تألیفی و قابل چاپ'))
    c.setFont('NotoArabic',10); c.drawRightString(w-42,h-145,fa('نام و نام خانوادگی: ........................................   تاریخ: ....................'))
    c.setLineWidth(.7); c.line(42,h-160,w-42,h-160)
    y=h-194
    for i,q in enumerate(questions(kind,title),1):
        c.setFont('NotoArabic',11); c.drawRightString(w-48,y,fa(str(i)+') '+q))
        y-=35
        c.setStrokeColorRGB(.82,.85,.88); c.line(55,y,w-48,y); y-=24
        if y<100: c.showPage(); y=h-70
    c.setFont('NotoArabic',9); c.drawRightString(w-42,45,fa('این برگه به‌صورت اختصاصی برای برنامهٔ آموزش با امیر تولید شده است.'))
    c.save()
for idx,(ch,title,kind,pages) in enumerate(LESSONS,1):
    slug=f'grade6-lesson-{idx:02d}.pdf'
    for out in OUTS: draw_pdf(out/slug,str(ch),title,pages,kind)
for ch,name in CHAPTERS.items():
    writer=PdfWriter()
    for idx,(lesson_ch,title,kind,pages) in enumerate(LESSONS,1):
        if lesson_ch==ch:
            writer.append(str(OUTS[0]/f'grade6-lesson-{idx:02d}.pdf'))
    chapter_path=OUTS[0]/f'grade6-chapter-{ch}.pdf'
    with chapter_path.open('wb') as target: writer.write(target)
    (OUTS[1]/chapter_path.name).write_bytes(chapter_path.read_bytes())
print(f'Generated {len(LESSONS)} original lesson PDFs and 7 complete chapter booklets in both web and app assets.');
